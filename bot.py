def parse_iiko(path):
    wb = load_workbook(path, data_only=True, read_only=True)
    ws = wb[wb.sheetnames[0]]

    period_text = str(ws["A3"].value or "").strip()

    # Поддерживаем все варианты iiko:
    # 1) "Период: с 01.09.2026 по 28.09.2026"
    # 2) "Дата: 01.10.2026-01.10.2026"
    # 3) "Дата: 01.10.2026"
    date_matches = __import__("re").findall(
        r"(\d{1,2})\.(\d{1,2})\.(\d{4})",
        period_text
    )

    if not date_matches:
        raise ValueError(
            f"Не смогла определить дату периода в строке A3: {period_text}"
        )

    # Берём последнюю дату в строке как конечную дату периода.
    day_s, month_s, year_s = date_matches[-1]
    day_end = int(day_s)
    month = int(month_s)
    year = int(year_s)

    # Проверка, что дата реальная.
    try:
        datetime(year, month, day_end)
    except ValueError:
        raise ValueError(
            f"Некорректная дата в строке A3: {period_text}"
        )

    blocks=[]
    enterprise=None
    subgroup=None
    items=[]

    for row in ws.iter_rows(min_row=4, values_only=True):
        a,b,c,d = row[:4]

        if a and str(a).strip() != "Итого":
            if items and enterprise and subgroup:
                blocks.append((enterprise, subgroup, items))
            enterprise = str(a).strip()
            subgroup = str(b).strip() if b else None
            items=[]

        elif enterprise and b and c is not None:
            if items and subgroup:
                blocks.append((enterprise, subgroup, items))
            subgroup = str(b).strip()
            items=[]

        elif enterprise and b and c is None:
            if items and subgroup:
                blocks.append((enterprise, subgroup, items))
                items=[]
            subgroup=None
            continue

        if enterprise and c is not None and d is not None:
            try:
                items.append((str(c).strip(), float(d)))
            except Exception:
                pass

    if items and enterprise and subgroup:
        blocks.append((enterprise, subgroup, items))

    return blocks, day_end, month, year



